import type { Rng } from './types';

/** Small seeded PRNG (mulberry32). Used by tests and dev presets. */
export function seededRng(seed: number): Rng {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Replays a fixed list of values, then repeats the last one. */
export function scriptedRng(values: readonly number[]): Rng {
  let i = 0;
  return () => {
    const v = values[Math.min(i, values.length - 1)] ?? 0;
    i += 1;
    return v;
  };
}

export const defaultRng: Rng = Math.random;
